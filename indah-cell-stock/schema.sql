-- SQL schema for Indah Cell Stock Counter

-- Create the main table for tracking stock
CREATE TABLE public.stock (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_cabang TEXT NOT NULL CHECK (nama_cabang IN ('Soko', 'Mbutoh')),
  produk TEXT NOT NULL DEFAULT 'HP',
  stok_pagi INT NOT NULL,
  stok_sekarang INT NOT NULL,
  tanggal DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Add a unique constraint to prevent duplicate entries for the same branch and date
ALTER TABLE public.stock
ADD CONSTRAINT unique_stock_entry UNIQUE (nama_cabang, tanggal);

-- Create the table for logging stock history
CREATE TABLE public.stock_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stock_id BIGINT NOT NULL REFERENCES public.stock(id) ON DELETE CASCADE,
  perubahan INT NOT NULL,
  stok_sebelum INT NOT NULL,
  stok_sesudah INT NOT NULL,
  -- user_id UUID REFERENCES auth.users(id), -- Optional: uncomment to track which user made the change
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Enable Row Level Security (RLS) for both tables
ALTER TABLE public.stock ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_history ENABLE ROW LEVEL SECURITY;

-- Create policies for the 'stock' table
CREATE POLICY "Allow public read access for stock"
ON public.stock FOR SELECT USING (true);

CREATE POLICY "Allow insert for authenticated users on stock"
ON public.stock FOR INSERT WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Allow update for authenticated users on stock"
ON public.stock FOR UPDATE USING (auth.role() = 'authenticated');

-- Create policies for the 'stock_history' table
CREATE POLICY "Allow read access for authenticated users on stock_history"
ON public.stock_history FOR SELECT USING (auth.role() = 'authenticated');

CREATE POLICY "Allow insert for authenticated users on stock_history"
ON public.stock_history FOR INSERT WITH CHECK (auth.role() = 'authenticated');


