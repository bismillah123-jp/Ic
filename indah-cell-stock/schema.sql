-- Create a function to update stock and log history atomically
CREATE OR REPLACE FUNCTION public.update_stock_and_log_history(
  p_stock_id BIGINT,
  p_perubahan INT
)
RETURNS VOID AS $$
DECLARE
  v_stok_sebelum INT;
  v_stok_sesudah INT;
BEGIN
  -- Get the current stock amount and lock the row
  SELECT stok_sekarang INTO v_stok_sebelum
  FROM public.stock
  WHERE id = p_stock_id
  FOR UPDATE;

  -- Calculate the new stock amount
  v_stok_sesudah := v_stok_sebelum + p_perubahan;

  -- Update the stock amount
  UPDATE public.stock
  SET stok_sekarang = v_stok_sesudah
  WHERE id = p_stock_id;

  -- Insert a record into the history table
  INSERT INTO public.stock_history (stock_id, perubahan, stok_sebelum, stok_sesudah)
  VALUES (p_stock_id, p_perubahan, v_stok_sebelum, v_stok_sesudah);
END;
$$ LANGUAGE plpgsql;

-- Create a function to create new daily stock entries based on the last available data
CREATE OR REPLACE FUNCTION public.create_daily_stock_entries()
RETURNS TEXT AS $$
DECLARE
  v_cabang TEXT;
  v_last_stock RECORD;
  v_today DATE := CURRENT_DATE;
  v_entries_created INT := 0;
  v_cabang_list TEXT[] := ARRAY['Mbutoh', 'Soko'];
BEGIN
  -- Loop through each branch
  FOREACH v_cabang IN ARRAY v_cabang_list
  LOOP
    -- Check if an entry for today already exists for the branch
    IF NOT EXISTS (SELECT 1 FROM public.stock WHERE nama_cabang = v_cabang AND tanggal = v_today) THEN
      -- Find the most recent stock record for the branch
      SELECT * INTO v_last_stock
      FROM public.stock
      WHERE nama_cabang = v_cabang
      ORDER BY tanggal DESC
      LIMIT 1;

      -- If a previous record exists, create a new one for today
      IF FOUND THEN
        INSERT INTO public.stock (nama_cabang, produk, stok_pagi, stok_sekarang, tanggal)
        VALUES (v_cabang, v_last_stock.produk, v_last_stock.stok_sekarang, v_last_stock.stok_sekarang, v_today);
        v_entries_created := v_entries_created + 1;
      END IF;
    END IF;
  END LOOP;

  RETURN 'Created ' || v_entries_created || ' new daily stock entries.';
END;
$$ LANGUAGE plpgsql;
